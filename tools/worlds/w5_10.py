from dsl import *
def build():
    L=Lv(10,"سيد الحمم",1900,1800); L.world=5
    L.ground(0,1900)
    L.cp(60); L.cp(420)
    # منصات ثابتة للمراوغة + منصات آمنة تتبدل مواقعها (مجموعتان بالتناوب)
    for x,y,w in [(200,360,100),(700,300,100),(1250,300,100),(1560,360,100)]: L.plat(x,y,w)
    L.van(480,360,90,300,0); L.van(930,360,90,300,150); L.van(1060,230,80,300,0); L.van(560,230,80,300,150)
    L.chest(730,286); L.crate(130,FLOOR,2); L.crate(1000,FLOOR,2)
    for x,y in [(240,330),(740,270),(1290,270),(1600,330),(520,330),(970,330)]: L.ember(x,y)
    L.embers_line(200,380,412,3)
    # فخاخ الساحة بحسب مرحلة الزعيم: أعمدة حمم من المرحلة 2، وأعمدة أطول وأسرع في المرحلة 3
    for x,p in ((620,0),(1120,70)): L.bossfount(x,44,90,150,60,p,2)
    for x,p in ((860,0),(1400,60)): L.bossfount(x,44,110,120,55,p,3)
    L.boss=("سيد الحمم",5,1550,520,60)
    return L
