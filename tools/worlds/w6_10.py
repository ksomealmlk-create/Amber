from dsl import *
def build():
    L=Lv(10,"ملك الجليد",1900,1800); L.world=6
    L.ground(0,1900); L.slip(0,1900)
    L.cp(60); L.cp(420)
    for x,y,w in [(220,360,100),(720,300,100),(1260,300,100),(1560,360,100)]: L.plat(x,y,w)
    # مناطق آمنة متغيرة: منصات تظهر وتختفي بالتناوب
    L.van(470,350,90,320,0); L.van(940,350,90,320,160); L.van(580,240,80,320,160); L.van(1080,240,80,320,0)
    L.chest(740,286); L.crate(140,FLOOR,3); L.crate(1010,FLOOR,3)
    for x,y in [(260,330),(760,270),(1300,270),(1600,330),(510,320),(980,320)]: L.ember(x,y)
    L.embers_line(200,380,412,3)
    # هجمات جليدية: أشواك جليد من المرحلة 2، وأعمدة أكثر وأسرع في المرحلة 3
    for x,p in ((620,0),(1120,70)): L.bossspikes(x,60,150,50,p,2)
    for x,p in ((860,0),(1400,60)): L.bossspikes(x,60,120,45,p,3)
    L.boss=("ملك الجليد",6,1550,520,60)
    return L
