from dsl import *
def build():
    L=Lv(7,"قاعة الفؤوس",4300,4200); L.world=4
    L.ground(0,4300)
    for x in (60,780,1745,2660,3455): L.cp(x)
    # أ: فأس سفلي ثم علوي ثم سفلي
    L.axe(300,180,380,60,100,0); L.axe(540,180,320,70,92,1.6); L.axe(1000,160,380,60,86,0.4)
    # ب: ثلاثة فؤوس متتابعة + ألواح ضغط
    L.axe(1180,160,380,60,84,2.2); L.axe(1380,170,320,70,80,4.0)
    L.plate(1560,0); L.trap(1620,70,28,0,80)
    # ج: تسلسل سريع: فؤوس سفلية وعلوية متناوبة
    for i in range(5):
        x=1850+i*150
        if i%2==0: L.axe(x,130,380,60,76+i*2,i*1.3)
        else: L.axe(x,130,320,70,76+i*2,i*1.3)
    L.plate(2500,1,18,80); L.trap(2560,60,28,1,80)
    # د: ممر مع هيكلين وفؤوس وأشواك
    L.axe(2700,170,380,60,90,0); L.skeleton(2900,2800,3050); L.tspikes(2980,60,120,60,0)
    L.axe(3100,150,320,70,80,2.8); L.axe(3250,140,380,60,78,0.8)
    # هـ: الختام: عمود فؤوس (سفلي وعلوي في نفس المكان)
    L.axe(3550,170,380,60,92,0); L.axe(3550,170,320,70,92,3.14)
    L.skeleton(3780,3650,3900); L.axe(3900,160,380,60,82,1.0); L.axe(4020,160,320,70,82,0)
    L.embers_line(100,700,412,6); L.embers_line(850,1650,412,8); L.embers_line(1750,2550,412,8)
    L.embers_line(2650,3350,412,7); L.embers_line(3450,4150,412,7)
    L.fog(1800,2600,.7)
    L.auto_runs()
    return L
