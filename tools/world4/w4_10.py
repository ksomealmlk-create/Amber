from dsl import *
def build():
    L=Lv(10,"ملك الهياكل",1800,1700); L.world=4
    L.ground(0,1800)
    L.cp(60); L.cp(420)
    # منصات للمراوغة والقفز فوق الموجات الأرضية
    for x,y,w in [(200,360,100),(520,300,100),(860,360,120),(1200,300,100),(1500,360,100),(690,225,80),(1040,225,80)]: L.plat(x,y,w)
    L.chest(540,286); L.crate(120); L.crate(980)
    for x,y in [(240,330),(560,270),(720,195),(900,330),(1080,195),(1240,270),(1540,330)]: L.ember(x,y)
    L.embers_line(200,380,412,3)
    # فخاخ الساحة بحسب مرحلة الملك: أشواك أرضية في المرحلة 2، فؤوس سفلية في المرحلة 3
    for x,p in ((640,0),(1120,70)): L.bossspikes(x,60,150,50,p,2)
    L.bossaxe(760,200,380,60,120,0,3); L.bossaxe(1300,200,380,60,120,3.0,3)
    L.fog(0,1800,.5)
    L.boss=("ملك الهياكل",13,1450,520,70)
    return L
