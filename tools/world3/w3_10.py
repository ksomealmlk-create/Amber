from dsl import *
def build():
    L=Lv(10,"عرش الفطر السام",1800,1700); L.world=3
    L.ground(0,1800)
    L.cp(60); L.cp(400)
    L.plat(240,350,110); L.plat(560,310,110); L.plat(1000,310,110); L.plat(1340,350,110)
    L.plat(400,240,80); L.plat(780,235,90); L.plat(1160,240,80)
    L.chest(600,296)
    L.crystal(120); L.crystal(900); L.crystal(1250)
    for x,y in [(280,320),(440,210),(820,205),(1040,280),(1200,210),(1380,320)]: L.ember(x,y)
    L.embers_line(150,360,412,4)
    # فخاخ تظهر بحسب مرحلة الزعيم: جذور في المرحلة 2، فطر سام في المرحلة 3
    for x,p in ((560,0),(1160,75)): L.bossroot(7,x,FLOOR-56,34,56,150,48,p,2)
    for x,p in ((360,0),(860,70),(1460,35)): L.bossroot(3,x,FLOOR-64,34,64,140,50,p,3)
    L.boss=("ملك الفطر السام",12,1450,520,64)
    return L
